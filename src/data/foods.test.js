describe('foods.json — 데이터 무결성', () => {
  it('400종 이상이어야 한다', () => {
    expect(foods.length).toBeGreaterThanOrEqual(400)
  })

  it('460종 이상이어야 한다 (음료·대용식 보강 이후)', () => {
    expect(foods.length).toBeGreaterThanOrEqual(460)
  })

  it('700종 이상이어야 한다 (대폭 보강 이후)', () => {
    expect(foods.length).toBeGreaterThanOrEqual(700)
  })

  it('모든 항목의 serving에 g 또는 ml 단위가 병기되어야 한다', () => {
    const missing = foods.filter((f) => !/\d+\s*(g|ml)/i.test(f.serving))
    expect(missing.map((f) => f.name)).toEqual([])
  })

  it('술을 제외한 전 항목에서 (탄×4+단×4+지×9)가 kcal의 ±40% 이내여야 한다', () => {
    const bad = []
    for (const f of foods) {
      if (f.category === '술') continue
      const computed = f.carbs * 4 + f.protein * 4 + f.fat * 9
      if (f.kcal === 0 && computed === 0) continue
      const diff = Math.abs(computed - f.kcal) / f.kcal
      if (diff > 0.4) bad.push({ name: f.name, kcal: f.kcal, computed })
    }
    expect(bad).toEqual([])
  })

  it('카테고리가 12개로 재분류되어야 한다', () => {
    const cats = new Set(foods.map((f) => f.category))
    expect(cats.size).toBe(12)
    for (const c of ['밥', '국찌개', '반찬', '고기생선', '면분식', '빵간식', '과일', '음료', '술', '양념소스', '간편식', '유제품']) {
      expect(cats.has(c)).toBe(true)
    }
  })

  it('name·aliases를 통틀어 중복이 없어야 한다', () => {
    const seen = new Map()
    const dupes = []
    for (const item of foods) {
      const strings = [item.name, ...(item.aliases || [])]
      for (const s of strings) {
        if (seen.has(s)) dupes.push({ string: s, with: seen.get(s) })
        seen.set(s, item.name)
      }
    }
    expect(dupes).toEqual([])
  })

  it('모든 항목이 필수 필드를 갖춰야 한다', () => {
    const fields = ['name', 'serving', 'kcal', 'carbs', 'protein', 'fat', 'category']
    const missing = foods.filter((item) => fields.some((f) => !(f in item)))
    expect(missing).toEqual([])
  })
})

